# Please keep this list alphabetically sorted. It makes it easier to check for double assignment of single-letter options
#
# We have the following naming suffix conventions:
#   Options are str values, or enum values
#   Flags are bool values
#   Numbers are int values
#
# Furthermore - start the name of the option/flag with the letter that is used as a short option. This way, by sorting them
# alphabetically we get those with the same letter next to each other.
#
# Convention:
#    lower case single letters are for most used arguments
#    upper case single letters are not used
#    other commands that are long to type get a short form with double dash, e.g. --file-transfer-jobs gets --ftj
#
