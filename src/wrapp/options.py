#
# We need a way to specialize the help text for each usage.
#
class SpecializeHelpTextOption:
    def __init__(self, default: Any, param_decls: List[str], help: Optional[str] = None, callback: Optional[Callable[..., Any]] = None):
        self.option = typer.Option(default, *param_decls, callback=callback)
        self._default_help = help

    def default_help(self):
        default = copy.deepcopy(self.option)
        default.help = self._default_help
        return default

    def better_help(self, help: str) -> Any:
        better = copy.deepcopy(self.option)
        better.help = help
        return better


@wrapp_public_api
class LsOutputFormat(str, Enum):
    """
    The type of output generated by the LS command

    Attributes:
        TSV: tab-separated values for use by catalog's --file-list
        normal: a nicely formatted table
        short: just the URLs detected
    """

    TSV = "tsv"
    normal = "normal"
    short = "short"

    def __str__(self):
        return self.value


def parse_auth_param(param: str) -> str:
    if not param.split(",")[0]:
        raise typer.BadParameter("The server URL in an auth parameter cannot be empty!")
    return param


def fail_if_tagging_service_is_not_available(param: bool):
    from wrapp.utils.storage import g_tagging_client_available

    if param and not g_tagging_client_available:
        raise typer.BadParameter("Tagging service is not available: omni.tagging.client is not part of the Python environment.")
    return param


